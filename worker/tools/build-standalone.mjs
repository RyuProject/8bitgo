/** Dependency-free single-file build, only for these local helper modules. */
import fs from 'node:fs/promises'
const root = new URL('../',import.meta.url)
const sources = []
for (const path of ['src/common.js','src/http.js','src/index.js']) {
  let source=await fs.readFile(new URL(path,root),'utf8')
  source=source.replace(/^import\s+[\s\S]*?\sfrom\s+['"][^'"]+['"]\s*\n/gm,'')
  if (path!=='src/index.js')source=source.replace(/^export /gm,'')
  sources.push(`\n// ===== ${path} =====\n${source}`)
}
await fs.mkdir(new URL('standalone/',root),{recursive:true})
await fs.writeFile(new URL('standalone/rom-worker.js',root),'// Generated by tools/build-standalone.mjs. Edit src/, then rebuild.\n'+sources.join('\n'))
await fs.copyFile(new URL('embed-vc/src/index.js',root),new URL('standalone/embed-worker.js',root))
console.log('Generated standalone/rom-worker.js and standalone/embed-worker.js')
